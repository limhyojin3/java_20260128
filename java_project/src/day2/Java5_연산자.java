package day2;

public class Java5_연산자 {

	public static void main(String[] args) {

		// 대입 연산자
		
		int a = 10;
		int b = 5;
		
		a += b; // a = a + b; //15
		System.out.println(a); 

		b -= 3; // b = b - 3; //2
		System.out.println(b);
		
		a *= 2; // 30
		System.out.println(a);
		
		
	}

}
