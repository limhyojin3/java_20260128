package day2;

public class Java8_비교연산자 {

	public static void main(String[] args) {

		// 크다, 작다, 같다, 다르다
		
		int a = 10;
		int b = 5;
		
		System.out.println(a > b);
		System.out.println(a < b);
		System.out.println(b > 3);
		System.out.println(a >= 10);
		System.out.println(b <= 5);
		System.out.println(a == b);
		System.out.println(a != b);
		
		System.out.println(!true);
		System.out.println(!(a == 10));
	}

}
